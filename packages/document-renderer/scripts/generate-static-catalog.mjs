import { readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);
const katexRoot = dirname(require.resolve('katex/package.json'));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const assets = [];
async function asset(packageName, base, sourcePath, path, mediaType) {
  const bytes = await readFile(join(base, sourcePath));
  assets.push({ path, mediaType, bytes: bytes.length, sha256: sha(bytes), source: { package: packageName, path: sourcePath } });
}
await asset('@pagelingo/document-renderer', root, 'static/offline-runtime.js', 'assets/offline-runtime.js', 'text/javascript');
await asset('@pagelingo/document-renderer', root, 'static/reader.css', 'assets/reader.css', 'text/css');
await asset('katex', katexRoot, 'dist/katex.min.css', 'assets/katex/katex.min.css', 'text/css');
await asset('katex', katexRoot, 'LICENSE', 'licenses/katex.txt', 'text/plain');
for (const name of (await readdir(join(katexRoot, 'dist/fonts'))).sort()) {
  const mediaType = name.endsWith('.woff2') ? 'font/woff2' : name.endsWith('.woff') ? 'font/woff' : 'font/ttf';
  await asset('katex', katexRoot, `dist/fonts/${name}`, `assets/katex/fonts/${name}`, mediaType);
}
assets.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
for (const [release, label] of [['s2-0.1.0', 'S2'], ['s3-0.2.0', 'S3']]) {
  const legacy = JSON.parse(await readFile(join(root, `compat/${release}/catalog.json`), 'utf8'));
  const legacyOutput = `// Frozen published ${label} metadata. Never recompute from current assets.\nimport type { TrustedAsset } from '../../static.js';\nexport const rendererVersion = '${legacy.version}';\nexport const rendererSha256 = '${legacy.codeSha256}';\nexport const trustedStaticAssets: readonly TrustedAsset[] = Object.freeze(${JSON.stringify(legacy.trustedAssets, null, 2)}.map(asset => Object.freeze({ ...asset, source: Object.freeze(asset.source) })) as TrustedAsset[]);\n`;
  await writeFile(join(root, `src/compat/${release}/catalog.ts`), legacyOutput);
}
const code = [];
async function sourceFiles(base, prefix = '') {
  const files = [];
  for (const entry of await readdir(join(base, prefix), { withFileTypes: true })) {
    const name = prefix + entry.name;
    if (entry.isDirectory()) files.push(...await sourceFiles(base, name + '/'));
    else if (name.endsWith('.ts') && !['static-catalog.ts', 'web-static-catalog.ts'].includes(name)) files.push(name);
  }
  return files.sort();
}
for (const packageName of ['document-renderer', 'document-contracts', 'translation-core']) {
  const base = fileURLToPath(new URL(`../../${packageName}/`, import.meta.url));
  for (const name of await sourceFiles(join(base, 'src'))) {
    const text = (await readFile(join(base, 'src', name), 'utf8')).replace(/\r\n?/g, '\n');
    code.push([`${packageName}/src/${name}`, sha(text)]);
  }
}
code.push(['trusted-assets', sha(JSON.stringify(assets))]);
const rendererSha256 = sha(JSON.stringify(code));
const { version } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const output = `// Generated by scripts/generate-static-catalog.mjs. Package-relative descriptors only.\nimport type { TrustedAsset } from './static.js';\nexport const rendererVersion = '${version}';\nexport const rendererSha256 = '${rendererSha256}';\nexport const trustedStaticAssets: readonly TrustedAsset[] = Object.freeze(${JSON.stringify(assets, null, 2)}.map(asset => Object.freeze({ ...asset, source: Object.freeze(asset.source) })) as TrustedAsset[]);\n`;
await writeFile(join(root, 'src/static-catalog.ts'), output);
