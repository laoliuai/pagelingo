import { test, expect } from '@playwright/test';
import { newReader } from './library-helpers';
import { archive, uploadArchive } from './web-helpers';
test('exports the opened immutable Web version and retries a lost acknowledgement across panel close', async ({ page }, testInfo) => {
  await newReader(page, 'download-web');
  const saved = await archive(page);
  const requests: Array<{ body: unknown; key: string | undefined }> = [];
  const receipts: string[] = [];
  await page.route(`**/api/v1/documents/${saved.documentId}/web-exports`, async route => {
    if (route.request().method() !== 'POST') return route.continue();
    requests.push({ body: route.request().postDataJSON(), key: route.request().headers()['idempotency-key'] });
    const response = await route.fetch(); receipts.push((await response.json()).id);
    if (requests.length === 1) return route.abort('connectionreset');
    return route.fulfill({ response });
  });
  await page.goto(`/library/${saved.documentId}`);
  const exportControl = page.locator('.export-panel > summary');
  expect((await exportControl.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await exportControl.focus(); await page.keyboard.press('Enter');
  await page.getByRole('button', { name: '生成新的离线包', exact: true }).click();
  await expect(page.getByRole('button', { name: '重试本次导出', exact: true })).toBeVisible();
  await page.getByText('离线下载', { exact: true }).click();
  await page.getByText('离线下载', { exact: true }).click();
  const { capture } = await import('../../../document-service/tests/helpers/web-capture');
  const newer = await uploadArchive(page,capture('<article><p>后来的来源版本，仍保留旧导出操作。</p></article>'),saved.documentId);
  await page.getByText('版本与目录',{exact:true}).click();
  await page.getByRole('button',{name:'刷新版本',exact:true}).click();
  await expect(page.getByLabel('阅读版本').locator(`option[value="${newer.readerVersionId}"]`)).toHaveCount(1);
  await page.getByLabel('阅读版本').selectOption(newer.readerVersionId);
  await page.getByRole('button', { name: '重试本次导出', exact: true }).click();
  await expect(page.getByRole('link', { name: '下载离线包', exact: true })).toBeVisible();
  expect(requests[1]).toEqual(requests[0]); expect(receipts[1]).toBe(receipts[0]);
  const download = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载离线包', exact: true }).click();
  await (await download).saveAs(testInfo.outputPath('selected-web.zip'));
  await page.screenshot({ path: testInfo.outputPath('private-download.png'), fullPage: true });
  await page.getByRole('button', { name: '生成新的离线包', exact: true }).click();
  await expect.poll(() => requests.length).toBe(3);
  expect(requests[2].key).not.toBe(requests[0].key);
  expect(requests[2].body).toEqual({ readerVersionId: newer.readerVersionId });
  await expect.poll(() => receipts.length).toBe(3);
  expect(receipts[2]).not.toBe(receipts[0]);
  await expect(page.getByRole('link', { name: '下载离线包', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 375, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('mobile-private-download.png'), fullPage: true });
});
test('downloads the original PDF and original selected package on a narrow screen',async({page},testInfo)=>{
  const {readingBundle,ingest}=await import('./bundle-helpers'); const {readFile}=await import('node:fs/promises');
  await newReader(page,'download-pdf'); const bundle=await readingBundle('partial'); const saved=await ingest(page,bundle);
  await page.setViewportSize({width:390,height:844}); await page.goto(`/library/${saved.documentId}`);
  await page.getByText('阅读版本与字号',{exact:true}).click();
  const pdfDownload=page.waitForEvent('download'); await page.getByRole('link',{name:'下载所选版本 PDF 原件',exact:true}).click();
  expect(await readFile((await (await pdfDownload).path())!)).toEqual(bundle.pdf);
  const zipDownload=page.waitForEvent('download'); await page.getByRole('link',{name:'下载所选版本原始阅读包',exact:true}).click();
  expect(await readFile((await (await zipDownload).path())!)).toEqual(bundle.buffer);
  await page.screenshot({path:testInfo.outputPath('mobile-original-downloads.png'),fullPage:true});
  await expect(page.getByText('离线下载',{exact:true})).toHaveCount(0);
});
